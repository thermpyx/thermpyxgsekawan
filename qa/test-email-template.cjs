/* Offline signup-email and setup-guide guard. No mail, HTTP request, or database access. */
"use strict";
const assert = require("node:assert/strict");
const fs = require("node:fs"), path = require("node:path");
const read = name => fs.readFileSync(path.join(__dirname, "..", name), "utf8");
const template = read("supabase/confirm-signup-email.html");
const guide = read("docs/EMAIL-THERMPYX.md");
const auth = read("js/content-store.js");
let checks = 0;

// Only Supabase's actual Go-template variables are accepted: invented names or
// a copied static code/link would otherwise make a plausible-looking dead email.
const variables = Array.from(template.matchAll(/{{\s*([^}]+?)\s*}}/g), match => match[1]);
assert.deepEqual(variables.sort(), [".ConfirmationURL", ".Token"]);
assert(!/{{|}}/.test(template.replace(/{{\s*\.(?:Token|ConfirmationURL)\s*}}/g, "")));
assert.match(template, /<p\b[^>]*>\s*{{\s*\.Token\s*}}\s*<\/p>/i);
checks++;

// Signup confirmation must have a working link alternative, using the URL
// generated by Supabase for this request rather than a site URL or stored token.
const links = Array.from(template.matchAll(/\bhref\s*=\s*(["'])(.*?)\1/g), match => match[2]);
assert.deepEqual(links, ["{{ .ConfirmationURL }}"]);
assert(!/<(?:script|iframe|form)\b|\bon\w+\s*=/i.test(template));
assert(!/sb_secret_|service_role|\beyJ[A-Za-z0-9_-]{25,}\./.test(template));
checks++;

assert.match(template, /<html\b[^>]*\blang="id"/i);
assert.match(template, /\blang="en"/i);
assert.match(template, /Masukkan kode/i);
assert.match(template, /Enter this code/i);
assert.match(template, /Konfirmasi akun\s*\/\s*Confirm account/i);
assert.match(template, /choose either method/i);
checks++;

// The operator must paste this into Confirm signup only. Password recovery
// requires Supabase's recovery ConfirmationURL, not the signup-code template.
assert.match(guide, /Jangan menyalin template Confirm signup ke Reset password/);
const resetInstruction = guide.split("\n").find(line => line.includes("Email pemulihan kata sandi harus tetap"));
assert(resetInstruction?.includes("{{ .ConfirmationURL }}"));
assert.match(guide, /Token pendaftaran tidak dapat digunakan untuk mengganti kata sandi/);
checks++;

// Detect stale dashboard callback instructions when the app changes its URL.
const site = "https://thermpyx.github.io/thermpyxgsekawan/";
for (const callback of ["index.html", "index.html?account=recovery"]) {
  assert(auth.includes(`new URL("${callback}", siteBase)`), `Review email guide after changing ${callback}`);
  assert(guide.includes(new URL(callback, site).href), `Missing allowed callback: ${callback}`);
  assert.equal(new URL(callback, site).hash, "", "Auth callback destinations must leave the fragment for GoTrue's session parameters");
}
assert(!/new URL\("index\.html[^"\n]*#/.test(auth), "Signup, resend and recovery must not send a hash in redirect_to");
assert(guide.includes(`| Site URL | \`${site}\` |`));
checks++;

// Accepted API requests do not prove delivery; existing confirmed users need
// sign-in/recovery, while project-specific delivery limits require Dashboard checks.
assert.match(guide, /Mendaftarkan ulang email lama[\s\S]*tanpa mengirim email konfirmasi baru/);
assert.match(guide, /Jika permintaan \*\*diterima\*\*[\s\S]*bukan jaminan/);
assert.match(guide, /batas default gabungan/);
assert.match(guide, /bukan hasil pemeriksaan kuota proyek Anda/);
assert.match(guide, /Authentication → Rate Limits/);
checks++;

console.log(`PASS ${checks} offline email checks: real Token/ConfirmationURL, safe dynamic link, ID/EN alternatives, separate reset template, matching callbacks and delivery diagnostics; no real emails sent`);
